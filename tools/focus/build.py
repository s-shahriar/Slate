#!/usr/bin/env python3
"""Regenerates Slate's Written » Focus assets from the web app (run after changing either source):
  assets/web/focus.css  <- general-quiz src/components/written/WrittenFocus.css (content part)
  assets/web/focus.js   <- general-quiz src/lib/qid.js + mathHighlight.js + focusMarks.js (same uids as the web)
Usage: python3 tools/focus/build.py"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
SLATE = os.path.normpath(os.path.join(HERE, '..', '..'))
WEB = os.path.normpath(os.path.join(SLATE, '..', 'general-quiz'))
OUT = os.path.join(SLATE, 'app/src/main/assets/web')

s = open(os.path.join(WEB, 'src/components/written/WrittenFocus.css')).read()
s = re.sub(r'/\* ── Group cards \(landing\).*?/\* ── Group tabs ─+ \*/.*?(?=\.fc-head)', '', s, flags=re.S)
s = s.replace('.fc-error { color: var(--text-3); text-align: center; margin: 40px 0; }\n', '')
s = s.replace('html:not([data-theme="dark"]) .fcw-page .topic-card,\n', '').replace('html:not([data-theme="dark"]) .fcw-page .topic-card { border: 1px solid var(--border-md); }\n', '')
s = s.replace('html:not([data-theme="dark"]) .fcw-page {', 'html:not([data-theme="dark"]) {')
s = s.replace('.fc-content [id] { scroll-margin-top: 76px; }', '.fc-content [id], .fc-head { scroll-margin-top: 8px; }')
head = ('/* Written » Focus page for Slate: GENERATED by tools/focus/build.py from general-quiz\n'
        '   src/components/written/WrittenFocus.css (content part). Colours come from the :root variables Slate injects. */\n'
        '.fc-root { --accent-soft: var(--accent); padding: 10px 12px 56px; }\n')
open(os.path.join(OUT, 'focus.css'), 'w').write(head + s)

q = open(os.path.join(WEB, 'src/lib/qid.js')).read()
norm = q[q.index('export function normalizeQ'):q.index('// cyrb53')]
cy = q[q.index('function cyrb53'):q.index('// Stable uid for a question')]
fu = q[q.index('export function focusUidOfText'):q.index('export function mathUidOfText')]
mh = open(os.path.join(WEB, 'src/lib/mathHighlight.js')).read()
mh = mh[mh.index('const SKIP'):mh.index('const COLOR_CLASSES')]
fm = open(os.path.join(WEB, 'src/lib/focusMarks.js')).read()
fm = fm[fm.index('export const UNIT'):fm.index('/** Marks the starred units')]
js = ('/* Written » Focus in Slate: tags the page exactly like the web (same uids), before controller.js / highlight.js start.\n'
      '   GENERATED by tools/focus/build.py from general-quiz src/lib/qid.js, mathHighlight.js and focusMarks.js. */\n(function () {\n'
      + '\n'.join(x.replace('export ', '') for x in (norm, cy, fu, mh, fm)) + '''
  var article = document.querySelector('.fc-content');
  var holder = document.querySelector('[data-gid]');
  if (!article) return;
  var roots = tagFocus(article, holder ? holder.getAttribute('data-gid') : '', focusUidOfText);
  // Written » GK: answers render covered; controller.js collects .qa-covered and the eye button switches cover mode.
  article.querySelectorAll('.qa-a').forEach(function (a) { a.classList.add('qa-covered'); });
  // controller.js stars '.mf-card[data-uid]' units and their ':scope > .mf-imp-btn'.
  roots.forEach(function (r) {
    tagMathBlocks(r, focusUidOfText);
    if (r.classList.contains('fc-unit')) {
      r.classList.add('mf-card');
      r.setAttribute('data-uid', r.getAttribute('data-hl-root'));
      var b = r.querySelector(':scope > .fc-imp-btn');
      if (b) b.classList.add('mf-imp-btn');
    }
  });
  // A topic link on a group page opens that topic's page (Slate navigates on "topic:<group>/<id>").
  article.addEventListener('click', function (e) {
    var a = e.target.closest && e.target.closest('[data-topic]');
    if (!a || !window.Slate || !window.Slate.onSection) return;
    e.preventDefault(); e.stopPropagation();
    window.Slate.onSection('topic:' + a.getAttribute('data-topic'));
  }, true);
  var base = window.setImportantOnly;
  window.setImportantOnly = function (on) { if (base) base(on); article.classList.toggle('fc-imp-only', !!on); };
})();
''')
open(os.path.join(OUT, 'focus.js'), 'w').write(js)
print('focus.css', len(head + s), 'focus.js', len(js))
