#!/usr/bin/env python3
"""Regenerates Slate's Written » Focus assets from the web app (run after changing either source):
  assets/web/focus.css  <- general-quiz src/components/written/WrittenFocus.css (content part)
  assets/web/focus.js   <- general-quiz src/lib/qid.js + mathHighlight.js + focusMarks.js (same uids as the web)
Usage: python3 tools/focus/build.py"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
SLATE = os.path.normpath(os.path.join(HERE, '..', '..'))
WEB = os.path.normpath(os.path.join(SLATE, '..', 'general-quiz'))
OUT = os.path.join(SLATE, 'app/src/main/assets/web')

s = open(os.path.join(WEB, 'src/components/written/WrittenFocus.css')).read()
s = re.sub(r'/\* ── Group cards \(landing\).*?/\* ── Group tabs ─+ \*/.*?(?=\.fc-head)', '', s, flags=re.S)
s = s.replace('.fc-error { color: var(--text-3); text-align: center; margin: 40px 0; }\n', '')
s = s.replace('html:not([data-theme="dark"]) .fcw-page .topic-card,\n', '').replace('html:not([data-theme="dark"]) .fcw-page .topic-card { border: 1px solid var(--border-md); }\n', '')
s = s.replace('html:not([data-theme="dark"]) .fcw-page {', 'html:not([data-theme="dark"]) {')
s = s.replace('.fc-content [id] { scroll-margin-top: 76px; }', '.fc-content [id], .fc-head { scroll-margin-top: 8px; }')
head = ('/* Written » Focus page for Slate: GENERATED by tools/focus/build.py from general-quiz\n'
        '   src/components/written/WrittenFocus.css (content part). Colours come from the :root variables Slate injects. */\n'
        '.fc-root { --accent-soft: var(--accent); padding: 10px 12px 56px; }\n'
        '/* Section jumps in Slate (FocusScreens.kt jumpSelect): the app dropdown look — accent-bordered field, rounded themed list. */\n'
        '.fc-head { overflow: visible; position: relative; z-index: 5; }\n'
        '.fc-dd { position: relative; flex: 1; min-width: 0; }\n'
        '.fc-dd-btn { width: 100%; min-height: 44px; display: flex; align-items: center; gap: 8px; padding: 8px 10px 8px 14px; border-radius: 14px;'
        ' background: var(--surface); color: var(--text-3); border: 1.5px solid color-mix(in srgb, var(--accent) 85%, transparent); font: inherit; font-size: 14.5px; text-align: left; }\n'
        '.fc-dd-btn .fc-dd-label { flex: 1; min-width: 0; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }\n'
        '.fc-dd.picked .fc-dd-btn { color: var(--text); font-weight: 600; }\n'
        '.fc-dd-btn svg { flex: none; color: var(--accent); transition: transform .18s; }\n'
        '.fc-dd.open .fc-dd-btn svg { transform: rotate(180deg); }\n'
        '.fc-dd-list { display: none; position: absolute; left: 0; right: 0; top: calc(100% + 6px); z-index: 40; max-height: 440px; overflow-y: auto;'
        ' padding: 6px; border-radius: 18px; background: var(--surface); border: 1px solid var(--border-md); box-shadow: 0 14px 34px rgba(0,0,0,.28); }\n'
        '.fc-dd.open .fc-dd-list { display: block; }\n'
        '.fc-dd-item { display: flex; align-items: center; width: 100%; min-height: 46px; margin: 2px 0; padding: 9px 12px; border: 0; border-radius: 12px;'
        ' background: transparent; color: var(--text); font: inherit; font-size: 15px; font-weight: 500; line-height: 1.45; text-align: left; }\n'
        '.fc-dd-item:active { background: var(--hover-bg, rgba(127,127,127,.12)); }\n'
        '.fc-dd-item.on { background: color-mix(in srgb, var(--accent) 13%, transparent); color: var(--accent); font-weight: 700; }\n'
        '.fc-dd-item.on::after { content: "✓"; margin-left: auto; padding-left: 10px; font-weight: 700; }\n'
        '/* Foot pager (FocusScreens.kt pagerHtml), like the web\'s TopicPager. */\n'
        '.topic-pager { display: grid; grid-template-columns: 1fr 1fr; gap: 10px; margin: 28px 0 8px; }\n'
        '.topic-pager-btn { display: flex; align-items: center; gap: 8px; min-height: 64px; padding: 10px 12px; text-align: left; border-radius: 14px;'
        ' border: 1.5px solid color-mix(in srgb, var(--accent) 45%, transparent); background: var(--surface); color: var(--text); font: inherit; }\n'
        '.topic-pager-btn.next { justify-content: flex-end; text-align: right; }\n'
        '.topic-pager-chev { flex: none; color: var(--accent); font-size: 26px; line-height: 1; font-weight: 600; }\n'
        '.topic-pager-txt { display: flex; flex-direction: column; min-width: 0; }\n'
        '.topic-pager-cap { font-size: 11.5px; font-weight: 700; color: var(--accent); }\n'
        '.topic-pager-name { font-size: 14px; font-weight: 600; line-height: 1.4; overflow: hidden; display: -webkit-box; -webkit-line-clamp: 2; -webkit-box-orient: vertical; }\n'
        '.fc-jumps { flex-wrap: nowrap !important; align-items: stretch; gap: 8px !important; }\n')
open(os.path.join(OUT, 'focus.css'), 'w').write(head + s)

q = open(os.path.join(WEB, 'src/lib/qid.js')).read()
norm = q[q.index('export function normalizeQ'):q.index('// cyrb53')]
cy = q[q.index('function cyrb53'):q.index('// Stable uid for a question')]
fu = q[q.index('export function focusUidOfText'):q.index('export function mathUidOfText')]
mh = open(os.path.join(WEB, 'src/lib/mathHighlight.js')).read()
mh = mh[mh.index('const SKIP'):mh.index('const COLOR_CLASSES')]
fm = open(os.path.join(WEB, 'src/lib/focusMarks.js')).read()
fm = fm[fm.index('export const UNIT'):fm.index('/** Marks the starred units')]
js = ('/* Written » Focus in Slate: tags the page exactly like the web (same uids), before controller.js / highlight.js start.\n'
      '   GENERATED by tools/focus/build.py from general-quiz src/lib/qid.js, mathHighlight.js and focusMarks.js. */\n(function () {\n'
      + '\n'.join(x.replace('export ', '') for x in (norm, cy, fu, mh, fm)) + '''
  var article = document.querySelector('.fc-content');
  var holder = document.querySelector('[data-gid]');
  if (!article) return;
  var roots = tagFocus(article, holder ? holder.getAttribute('data-gid') : '', focusUidOfText);
  // controller.js stars '.mf-card[data-uid]' units and their ':scope > .mf-imp-btn'.
  roots.forEach(function (r) {
    tagMathBlocks(r, focusUidOfText);
    if (r.classList.contains('fc-unit')) {
      r.classList.add('mf-card');
      r.setAttribute('data-uid', r.getAttribute('data-hl-root'));
      var b = r.querySelector(':scope > .fc-imp-btn');
      if (b) b.classList.add('mf-imp-btn');
    }
  });
  // A topic link on a group page opens that topic's page (Slate navigates on "topic:<group>/<id>").
  article.addEventListener('click', function (e) {
    var a = e.target.closest && e.target.closest('[data-topic]');
    if (!a || !window.Slate || !window.Slate.onSection) return;
    e.preventDefault(); e.stopPropagation();
    window.Slate.onSection('topic:' + a.getAttribute('data-topic'));
  }, true);
  // The section dropdown (FocusScreens.kt jumpSelect): open/close, pick = jump + mark it current; a tap outside closes.
  // vh is 0 in this WebView (it is measured before the view has a height), so size the list in px on open.
  window.fcDD = function (btn) {
    var dd = btn.parentElement, list = dd.querySelector('.fc-dd-list');
    var below = window.innerHeight - btn.getBoundingClientRect().bottom - 16;
    list.style.maxHeight = Math.max(260, Math.min(480, below)) + 'px';
    dd.classList.toggle('open');
  };
  window.fcPick = function (item, id) {
    var dd = item.closest('.fc-dd');
    dd.classList.remove('open'); dd.classList.add('picked');
    dd.querySelector('.fc-dd-label').textContent = item.textContent;
    dd.querySelectorAll('.fc-dd-item').forEach(function (x) { x.classList.toggle('on', x === item); });
    if (window.scrollToId) window.scrollToId(id);
  };
  document.addEventListener('click', function (e) {
    document.querySelectorAll('.fc-dd.open').forEach(function (dd) { if (!dd.contains(e.target)) dd.classList.remove('open'); });
  }, true);
  var base = window.setImportantOnly;
  window.setImportantOnly = function (on) { if (base) base(on); article.classList.toggle('fc-imp-only', !!on); };
})();
''')
open(os.path.join(OUT, 'focus.js'), 'w').write(js)
print('focus.css', len(head + s), 'focus.js', len(js))
